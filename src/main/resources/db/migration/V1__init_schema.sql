-- RideX initial schema. Enums are varchar + CHECK (mapped with @Enumerated(STRING)).
-- Foreign keys use the default NO ACTION, so ride history can never be deleted by accident.

-- Great-circle (Haversine) distance in km, used to find drivers near a pickup point.
create function distance_km(lat1 double precision, lng1 double precision,
                            lat2 double precision, lng2 double precision)
    returns double precision
    language sql immutable as
$$
select 6371 * 2 * asin(least(1, sqrt(
        power(sin(radians(lat2 - lat1) / 2), 2) +
        cos(radians(lat1)) * cos(radians(lat2)) * power(sin(radians(lng2 - lng1) / 2), 2))))
$$;

create table users (
    id            bigint generated by default as identity primary key,
    full_name     varchar(100) not null,
    email         varchar(150) not null unique,
    phone         varchar(15)  not null unique,
    password_hash varchar(100) not null,
    role          varchar(20)  not null check (role in ('PASSENGER', 'DRIVER', 'ADMIN')),
    status        varchar(20)  not null default 'ACTIVE' check (status in ('ACTIVE', 'BLOCKED')),
    created_at    timestamptz  not null default now()
);
create index ix_users_role on users (role);

-- Shared primary key: a driver's id is their users.id
create table driver_profiles (
    user_id          bigint primary key references users (id),
    license_number   varchar(30) not null unique,
    license_expiry   date,
    approval_status  varchar(20) not null default 'PENDING'
                     check (approval_status in ('PENDING', 'APPROVED', 'REJECTED')),
    rejection_reason varchar(255),
    online           boolean     not null default false,
    approved_at      timestamptz
);
create index ix_driver_profiles_approval on driver_profiles (approval_status);

create table vehicles (
    id                  bigint generated by default as identity primary key,
    driver_id           bigint      not null unique references driver_profiles (user_id),
    registration_number varchar(20) not null unique,
    make                varchar(50) not null,
    model               varchar(50) not null,
    color               varchar(30) not null,
    manufacture_year    int         not null check (manufacture_year between 1990 and 2100),
    status              varchar(20) not null default 'ACTIVE' check (status in ('ACTIVE', 'INACTIVE'))
);

create table driver_documents (
    id           bigint generated by default as identity primary key,
    driver_id    bigint       not null references driver_profiles (user_id),
    doc_type     varchar(20)  not null check (doc_type in ('LICENSE', 'RC', 'ID_PROOF')),
    file_name    varchar(255) not null,
    content_type varchar(100) not null,
    data         bytea        not null,
    uploaded_at  timestamptz  not null default now(),
    unique (driver_id, doc_type)
);

create table driver_locations (
    driver_id  bigint primary key references driver_profiles (user_id),
    latitude   double precision not null check (latitude between -90 and 90),
    longitude  double precision not null check (longitude between -180 and 180),
    updated_at timestamptz      not null default now()
);
create index ix_driver_locations_lat_lng on driver_locations (latitude, longitude);

create table bookings (
    id             bigint generated by default as identity primary key,
    passenger_id   bigint           not null references users (id),
    driver_id      bigint references driver_profiles (user_id),
    pickup_address varchar(255)     not null,
    pickup_lat     double precision not null check (pickup_lat between -90 and 90),
    pickup_lng     double precision not null check (pickup_lng between -180 and 180),
    drop_address   varchar(255)     not null,
    drop_lat       double precision not null check (drop_lat between -90 and 90),
    drop_lng       double precision not null check (drop_lng between -180 and 180),
    distance_km    numeric(7, 2)    not null check (distance_km >= 0),
    duration_min   int              not null check (duration_min >= 0),
    fare           numeric(10, 2)   not null check (fare >= 0),
    route_path     text,            -- JSON array of [lat, lng] points
    status         varchar(20)      not null default 'REQUESTED'
                   check (status in ('REQUESTED', 'ACCEPTED', 'STARTED', 'COMPLETED', 'CANCELLED', 'EXPIRED')),
    otp            varchar(4)       not null,
    requested_at   timestamptz      not null default now(),
    accepted_at    timestamptz,
    started_at     timestamptz,
    completed_at   timestamptz,
    cancelled_at   timestamptz,
    cancelled_by   varchar(20) check (cancelled_by in ('PASSENGER', 'DRIVER', 'ADMIN')),
    version        bigint           not null default 0,
    -- once a driver has accepted, the booking must name that driver
    constraint ck_bookings_driver check (status in ('REQUESTED', 'EXPIRED', 'CANCELLED') or driver_id is not null)
);
-- A driver can hold only one active ride; a passenger only one open booking.
create unique index ux_bookings_driver_active on bookings (driver_id) where status in ('ACCEPTED', 'STARTED');
create unique index ux_bookings_passenger_open on bookings (passenger_id) where status in ('REQUESTED', 'ACCEPTED', 'STARTED');
create index ix_bookings_status_requested on bookings (status, requested_at);
create index ix_bookings_passenger on bookings (passenger_id, requested_at desc);
create index ix_bookings_driver on bookings (driver_id, requested_at desc);

-- Drivers who declined a request never see it again
create table booking_rejections (
    booking_id  bigint      not null references bookings (id),
    driver_id   bigint      not null references driver_profiles (user_id),
    rejected_at timestamptz not null default now(),
    primary key (booking_id, driver_id)
);

create table payments (
    id             bigint generated by default as identity primary key,
    booking_id     bigint         not null unique references bookings (id),
    amount         numeric(10, 2) not null check (amount >= 0),
    commission     numeric(10, 2) not null default 0 check (commission >= 0),
    driver_earning numeric(10, 2) not null default 0 check (driver_earning >= 0),
    method         varchar(10)    not null check (method in ('CASH', 'UPI')),
    status         varchar(10)    not null default 'PENDING' check (status in ('PENDING', 'PAID', 'VOID')),
    paid_at        timestamptz
);
create index ix_payments_paid_at on payments (paid_at) where status = 'PAID';

create table ratings (
    id         bigint generated by default as identity primary key,
    booking_id bigint       not null unique references bookings (id),
    driver_id  bigint       not null references driver_profiles (user_id),
    stars      int          not null check (stars between 1 and 5),
    comment    varchar(500),
    created_at timestamptz  not null default now()
);
create index ix_ratings_driver on ratings (driver_id);
